export function andList(xs) {
    return xs.length < 2 ? xs.join('') : t('tv-and', {list: xs.slice(0, -1).join(', '), last: xs.at(-1)});
}


// How long recordings are kept (LOG_RETENTION_DAYS): `key` with {days}, or `key`-all when 0 keeps
// them all. The privacy page and the club settings both say it this way.
export function retentionText(key, days) {
    return days > 0 ? t(key, {days}) : t(`${key}-all`);
}


// How long the operator keeps backups (BACKUP_RETENTION_MONTHS): '1 month', '6 months'.
export function monthsText(n) {
    return n === 1 ? '1 month' : `${n} months`;
}


// The whole page of the admin pages (admin.mjs): the shared stylesheet's .plain section,
// no script. The title is always the neutral "Paceline" (spec §5); `heading` is plain text.
// `refresh` (a path, e.g. '/manage') loads that path every 30 s (the club page around a race start).
// Always with a target: a bare refresh reloads the document's URL, which may be a POST action.
export function page(heading, body, {refresh = null} = {}) {
    return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="color-scheme" content="light dark">
${refresh ? `<meta http-equiv="refresh" content="30;url=${esc(refresh)}">\n` : ''}<title>Paceline</title><link rel="stylesheet" href="${cssHref}"></head>
<body class="plain"><h1>${esc(heading)}</h1>
${body}
</body></html>`;
}


// 'captain@example.org' -> 'c…@example.org' (the first character, …, @ and the domain).
export function maskAddress(email) {
    const s = String(email ?? '');
    const at = s.lastIndexOf('@');
    const first = [...s][0] ?? '';
    return at < 0 ? `${first}…` : `${first}…@${s.slice(at + 1)}`;
}
