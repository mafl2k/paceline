export function fmt(key, vars = {}) {
    const tpl = S[key];
    if (typeof tpl !== 'string') {
        throw new Error(`Unknown string: ${key}`);
    }
    return tpl.replace(/\{(\w+)\}/g, (m, k) => Object.hasOwn(vars, k) ? String(vars[k]) : m);
}
